const fs = require('fs');
const Database = require('better-sqlite3');
const path = process.argv[2];
const outPath = process.argv[3];
const db = new Database(path, { readonly: true });

function quoteIdent(name) {
  return '"' + String(name).replace(/"/g, '""') + '"';
}
function sqlValue(value) {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (Buffer.isBuffer(value)) return "X'" + value.toString('hex') + "'";
  if (value instanceof Date) return "'" + value.toISOString().replace(/'/g, "''") + "'";
  if (typeof value === 'string') return "'" + value.replace(/'/g, "''") + "'";
  return "'" + String(value).replace(/'/g, "''") + "'";
}

const objects = db.prepare("SELECT type, name, sql FROM sqlite_master WHERE type IN ('table','index','view','trigger') AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 WHEN 'trigger' THEN 3 ELSE 4 END, name").all();
const lines = ['-- SQLite dump generated by better-sqlite3', '-- Source: ' + path, ''];
for (const obj of objects) {
  if (obj.type === 'table' && obj.sql) {
    lines.push(obj.sql + ';');
    const tableName = obj.name;
    const columns = db.prepare(`PRAGMA table_info(${quoteIdent(tableName)})`).all();
    const colNames = columns.map(c => quoteIdent(c.name));
    if (colNames.length > 0) {
      const rows = db.prepare(`SELECT * FROM ${quoteIdent(tableName)}`).all();
      for (const row of rows) {
        const values = colNames.map((col, idx) => sqlValue(row[columns[idx].name]));
        lines.push(`INSERT INTO ${quoteIdent(tableName)} (${colNames.join(', ')}) VALUES (${values.join(', ')});`);
      }
    }
    lines.push('');
  } else if (obj.sql) {
    lines.push(obj.sql + ';');
    lines.push('');
  }
}
fs.writeFileSync(outPath, lines.join('\n'));
console.log('Wrote ' + outPath);
db.close();
